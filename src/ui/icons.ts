/**
 * The neutral "rosette" mark: a guilloche (the fine interlaced line work printed on banknotes
 * and cheques), drawn as phase-shifted wavy rings. Pure decoration, generated once.
 */
export function rosette(size = 120, rings: Array<[radius: number, amp: number, waves: number, copies: number]> = [
  [0.8, 0.12, 18, 4],
  [0.5, 0.1, 12, 3],
], steps = 360): string {
  const c = size / 2;
  const paths: string[] = [];
  rings.forEach(([radius, amp, waves, copies], k) => {
    for (let j = 0; j < copies; j++) {
      const phase = (j / copies) * Math.PI * 2;
      let d = "";
      for (let i = 0; i <= steps; i++) {
        const t = (i / steps) * Math.PI * 2;
        const rr = c * (radius + amp * Math.sin(waves * t + phase));
        d += `${i ? "L" : "M"}${(c + rr * Math.cos(t)).toFixed(1)} ${(c + rr * Math.sin(t)).toFixed(1)}`;
      }
      paths.push(`<path class="ring ring-${k}" pathLength="1" d="${d}Z"/>`);
    }
  });
  return `<svg viewBox="0 0 ${size} ${size}" aria-hidden="true" focusable="false">${paths.join("")}</svg>`;
}
